#!/usr/bin/env node
/**
 * Regenerates `locations.ts` from Python's bundled `doc_locations.json`.
 *
 * The Python side owns the mapping: it is generated from the idfkit-docs search
 * index and is stable across EnergyPlus versions. This script is the only way
 * the TypeScript copy is allowed to change, so the two cannot drift by hand.
 *
 *   node packages/core/src/docs-url/generate-locations.mjs [path/to/doc_locations.json]
 *
 * The default source is a sibling checkout of the idfkit repository.
 *
 * ENCODING
 *
 * The JSON is 95 KB because it repeats two things: the section path, once per
 * object type sharing it, and the anchor, which is a pure function of the
 * object type (`_object_anchor` in docs.py). Neither has to be stored. Grouping
 * types by section path and recomputing the anchor is exact rather than
 * approximate, and the script proves it is exact before writing: every entry is
 * re-expanded and compared byte for byte against the JSON, and the script fails
 * without writing if a single one differs. If a future mapping breaks the
 * anchor rule, this fails loudly here instead of emitting a wrong URL.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

const source =
  process.argv[2] ?? here('../../../../../idfkit/src/idfkit/schemas/doc_locations.json');
const target = here('./locations.ts');

/** Mirrors `_object_anchor` in idfkit/src/idfkit/docs.py. */
const anchorOf = (objType) => objType.toLowerCase().replace(/[:/() ]/g, '');

const raw = JSON.parse(readFileSync(source, 'utf8'));

// Group object types by section path, checking the anchor rule as we go.
/** @type {Map<string, string[]>} */
const byPath = new Map();
for (const [objType, location] of Object.entries(raw)) {
  const hash = location.indexOf('#');
  if (hash === -1) {
    throw new Error(`No anchor in doc location for ${objType}: ${location}`);
  }
  const path = location.slice(0, hash + 1);
  const anchor = location.slice(hash + 1);
  if (anchor !== anchorOf(objType)) {
    throw new Error(
      `Anchor for ${objType} is ${anchor}, not the ${anchorOf(objType)} the ` +
        `anchor rule derives. The compact encoding cannot represent it; ` +
        `store the full location for this entry instead.`
    );
  }
  if (objType.includes('\t')) throw new Error(`Tab in object type name: ${objType}`);
  let types = byPath.get(path);
  if (types === undefined) byPath.set(path, (types = []));
  types.push(objType);
}

// Prove the encoding round-trips before writing anything.
/** @type {Record<string, string>} */
const expanded = {};
for (const [path, types] of byPath) {
  for (const objType of types) expanded[objType] = `${path}${anchorOf(objType)}`;
}
const missing = Object.keys(raw).filter((k) => expanded[k] !== raw[k]);
if (missing.length > 0 || Object.keys(expanded).length !== Object.keys(raw).length) {
  throw new Error(`Encoding is not exact for ${missing.length} entries: ${missing.slice(0, 5)}`);
}

const entries = [...byPath]
  .map(([path, types]) => `  ['${path}', '${types.join('\\t')}'],`)
  .join('\n');

const output = `// Generated by generate-locations.mjs from idfkit's doc_locations.json. Do not edit.
// ${Object.keys(raw).length} object types across ${byPath.size} section paths.

/**
 * Documentation section paths, each paired with the tab-separated object types
 * documented there.
 *
 * Anchors are omitted because they are a pure function of the object type; the
 * generator verifies that for every entry before writing this file. Storing the
 * mapping this way costs a third of the JSON it came from, which matters
 * because \`@idfkit/core\` is loaded in browsers.
 *
 * @internal
 */
export const DOC_LOCATIONS: readonly (readonly [path: string, types: string])[] = [
${entries}
];
`;

// Formatted here rather than left for `npm run format` to fix, so that
// regenerating never shows up as a formatting failure in CI.
const formatted = await format(output, {
  ...(await resolveConfig(target)),
  filepath: target,
});

writeFileSync(target, formatted);
console.log(
  `Wrote ${target}: ${Object.keys(raw).length} types, ${byPath.size} paths, ` +
    `${(formatted.length / 1024).toFixed(1)} KB (from ${(readFileSync(source).length / 1024).toFixed(1)} KB JSON)`
);
