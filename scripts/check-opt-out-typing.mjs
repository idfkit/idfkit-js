#!/usr/bin/env node
/**
 * The opt-out typing gate (task T100, FR-040, SC-014).
 *
 * THE CRITERION
 *
 * `contracts/distribution.md`: "Zero bytes of type packages installed, library
 * fully functional", against a clean install with no type package. Both halves
 * matter, and they pull in opposite directions: it is trivial to ship zero
 * declaration bytes by breaking the library, and trivial to make the library
 * work by shipping all 5.3 MB.
 *
 * WHAT THE SPLIT IS FOR
 *
 * `packages/core/src/types/v26-1.ts` was 2.6 MB and `v9-4.ts` was 2.4 MB,
 * against roughly 170 KB of everything else: core was about 97 percent
 * generated type declarations. They now live in `@idfkit/types-v26-1` and
 * `@idfkit/types-v9-4`, which nothing depends on. A document with no map is
 * typed through `UntypedMap`, so every operation works and field names are
 * accepted as strings; the map only adds static checking of one EnergyPlus
 * version's field names.
 *
 * So SC-014's claim is that declining 5.3 MB costs a reader nothing except
 * completion in their editor. This gate checks it four ways:
 *
 *   1. NOT INSTALLED. Neither type package is on disk, and Node cannot resolve
 *      either name from the fixture. Resolution is asked for, not assumed: a
 *      package hoisted from somewhere above would satisfy an import while the
 *      fixture's own tree looked clean.
 *
 *   2. ZERO GENERATED BYTES. Every `.d.ts` on disk is accounted for, and none
 *      of them carries the generator's banner. That banner is the honest test:
 *      "no type package directory" would be satisfied by a build that inlined
 *      the generated map back into `@idfkit/core`, which is the regression the
 *      split exists to prevent and which no directory check would see.
 *
 *   3. FULLY FUNCTIONAL. A strict TypeScript project that parses, reads a
 *      field, mutates and writes, with no map anywhere, type-checks and runs.
 *
 *   4. THE OPT-IN STILL WORKS. A second fixture installs `@idfkit/types-v26-1`
 *      and parameterises a document with its `TypeMap`. This is the control:
 *      without it, all three checks above would pass just as happily if the
 *      type packages were broken or empty, and SC-014 would be measuring an
 *      absence that nobody could ever turn into a presence.
 *
 * The control also puts the price of opting in on the record. SC-014 does not
 * measure it, in the same way SC-012 does not measure an opted-into weather
 * install, but the number belongs in the log next to the zero.
 *
 * Exit codes: 0 the opt-out is real and free, 1 it is not, 2 could not run.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  CannotRun,
  FACADE,
  Finding,
  REPO,
  TYPE_PACKAGES,
  fixtureRoot,
  installSharedNameOrFail,
  kib,
  mib,
  packWorkspaces,
  resolveFrom,
  run,
  runInFixture,
  totals,
  verdict,
  walkFiles,
  writeJson,
} from './lib/clean-install.mjs';

/**
 * The first line every generated map carries, from `scripts/emit-types.mjs`.
 *
 * Matching the banner rather than the filename is what makes finding 2 above
 * worth having: it catches the generated bytes wherever they end up, including
 * back inside `@idfkit/core` under a different name.
 */
const GENERATED_BANNER = /Generated by scripts\/emit-types\.mjs/;

/** A strict project that uses the library with no type map at all. */
const OPT_OUT_TS = `
import { parseIdf, writeIdf, type IdfDocument, type UntypedMap } from 'idfkit';
import { schemas } from 'idfkit/node';

// No TypeMap anywhere. UntypedMap is the default parameter, so field names are
// accepted as strings and every operation below is statically fine.
export async function roundTrip(source: string): Promise<string> {
  const schema = await schemas().load('26.1.0');
  const parsed = parseIdf(source, schema);
  const document: IdfDocument<UntypedMap> = parsed.document;
  const building = document.require('Building', 'Tower');
  const axis: unknown = building.get('north_axis');
  building.set('north_axis', typeof axis === 'number' ? axis + 1 : 30);
  return writeIdf(document);
}
`;

const OPT_OUT_JS = `
import { parseIdf, writeIdf } from 'idfkit';
import { schemas } from 'idfkit/node';

const schema = await schemas().load('26.1.0');
const parsed = parseIdf('Version,26.1;\\n\\nBuilding,\\n  Tower;\\n', schema);
const building = parsed.document.require('Building', 'Tower');
building.set('north_axis', 30);
const text = writeIdf(parsed.document);
if (!text.includes('Building') || !text.includes('30')) {
  console.error('round trip lost the document: ' + JSON.stringify(text));
  process.exit(1);
}
console.log('OK ' + text.replace(/\\s+/g, ' ').trim());
`;

/** The control: the same library, parameterised by an installed map. */
const OPT_IN_TS = `
import { parseIdf, type IdfDocument } from 'idfkit';
import { schemas } from 'idfkit/node';
import type { TypeMap } from '@idfkit/types-v26-1';

// The annotation is the assertion. Without the map, ceiling_height is a
// StoredValue reached through a string; with it, this exact union is what
// 26.1.0 declares, sentinels included. A tsc that accepts this line has really
// read the installed map, which is what makes fixture 4 a control rather than
// a second way of importing nothing.
export async function ceilingHeight(
  source: string
): Promise<number | 'Autosize' | 'Autocalculate' | undefined> {
  const schema = await schemas().load('26.1.0');
  const parsed = parseIdf<TypeMap>(source, schema);
  const document: IdfDocument<TypeMap> = parsed.document;
  return document.all('Zone').first?.ceiling_height;
}
`;

function tsconfig(include) {
  return {
    compilerOptions: {
      module: 'nodenext',
      moduleResolution: 'nodenext',
      target: 'es2022',
      lib: ['es2023'],
      strict: true,
      noEmit: true,
      skipLibCheck: false,
      types: [],
    },
    include,
  };
}

function typecheck(dir) {
  const tsc = join(REPO, 'node_modules', '.bin', 'tsc');
  if (!existsSync(tsc)) {
    throw new CannotRun(`no TypeScript at ${tsc}. Run \`npm ci\`.`);
  }
  try {
    execFileSync(tsc, ['--noEmit', '--project', join(dir, 'tsconfig.json')], {
      cwd: dir,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { code: 0, output: '' };
  } catch (error) {
    return { code: error.status ?? 1, output: `${error.stdout ?? ''}${error.stderr ?? ''}` };
  }
}

async function main() {
  const scratch = fixtureRoot('opt-out-typing');
  try {
    const { tarballs } = packWorkspaces(scratch.tarballDir);
    const findings = [];

    // ---- The opt-out install ----------------------------------------------
    const out = installSharedNameOrFail(scratch, tarballs, { label: 'no-type-package' });
    const files = walkFiles(out.modules);
    const total = totals(files);

    // 1. Not installed, asserted by resolution.
    for (const name of TYPE_PACKAGES) {
      const probe = resolveFrom(out.dir, name);
      const dir = join(out.modules, ...name.split('/'));
      if (probe.resolved !== null || existsSync(dir)) {
        findings.push(
          new Finding(
            `${name} is installed by the shared name`,
            `Resolved to ${probe.resolved ?? dir}. FR-040 makes the generated maps opt-in and ` +
              'installed by their own names; nothing may depend on one. Between them they are ' +
              '5.3 MB against roughly 170 KB of everything else.'
          )
        );
      }
    }

    // 2. Zero generated bytes, wherever they might be.
    const declarations = files.filter((file) => file.relative.endsWith('.d.ts'));
    const generated = declarations.filter((file) => {
      try {
        return GENERATED_BANNER.test(readFileSync(file.path, 'utf8').slice(0, 4096));
      } catch {
        return false;
      }
    });
    const generatedBytes = generated.reduce((sum, file) => sum + file.bytes, 0);
    if (generated.length > 0) {
      findings.push(
        new Finding(
          `${generated.length} generated declaration file(s) are on disk, ${mib(generatedBytes)}`,
          `${generated
            .slice(0, 5)
            .map((f) => f.relative)
            .join(', ')}. Each carries the emit-types.mjs banner. A reader who installed no type ` +
            'package is paying for one anyway, which is SC-014 exactly. Note that this catches ' +
            'the generated map wherever it ends up, including inlined back into @idfkit/core, ' +
            'which is where it used to be.'
        )
      );
    }

    // 3. Fully functional.
    writeFileSync(join(out.dir, 'app.ts'), OPT_OUT_TS);
    writeJson(join(out.dir, 'tsconfig.json'), tsconfig(['app.ts']));
    const outTypes = typecheck(out.dir);
    if (outTypes.code !== 0) {
      const diagnostics = outTypes.output.trim().split('\n').filter(Boolean);
      findings.push(
        new Finding(
          'a project with no type package installed does not type-check',
          `tsc reported ${diagnostics.length} diagnostic(s): ${diagnostics.slice(0, 4).join(' | ')}. ` +
            'A document with no map is typed through UntypedMap: field names are accepted as ' +
            'strings and every operation is available. If that no longer holds, declining the ' +
            'type packages is no longer free and SC-014 is not met.'
        )
      );
    }
    const outRun = runInFixture(out.dir, 'app.mjs', OPT_OUT_JS);
    if (outRun.code !== 0) {
      findings.push(
        new Finding(
          'a project with no type package installed does not run',
          `Exit ${outRun.code}: ${(outRun.stderr || outRun.stdout).trim().split('\n').slice(-3).join(' ')}`
        )
      );
    }

    // ---- 4. The control: opting in still works ----------------------------
    const optIn = installSharedNameOrFail(scratch, tarballs, {
      label: 'with-type-package',
      also: [TYPE_PACKAGES[0]],
    });
    writeFileSync(join(optIn.dir, 'app.ts'), OPT_IN_TS);
    writeJson(join(optIn.dir, 'tsconfig.json'), tsconfig(['app.ts']));
    const inTypes = typecheck(optIn.dir);
    if (inTypes.code !== 0) {
      const diagnostics = inTypes.output.trim().split('\n').filter(Boolean);
      findings.push(
        new Finding(
          `installing ${TYPE_PACKAGES[0]} does not give a working type map`,
          `tsc reported ${diagnostics.length} diagnostic(s): ${diagnostics.slice(0, 4).join(' | ')}. ` +
            'This is the control for the three findings above: an absence nobody can turn into ' +
            'a presence is not an opt-out, it is a missing feature.'
        )
      );
    }
    const inTotal = totals(walkFiles(optIn.modules));

    console.log('idfkit-js opt-out typing gate (FR-040, SC-014)');
    console.log(`  installed    npm install ${FACADE}, no type package`);
    console.log(`  tree         ${total.count} files, ${kib(total.apparent)}`);
    console.log('');
    for (const name of TYPE_PACKAGES) {
      const probe = resolveFrom(out.dir, name);
      const onDisk = existsSync(join(out.modules, ...name.split('/')));
      // Both, and neither on its own. A declarations-only package exposes only
      // a `types` condition, so `import.meta.resolve` reports it unresolvable
      // whether or not it is installed; the directory is what says it is there.
      console.log(
        `  ${name.padEnd(22)} ${onDisk ? 'ON DISK' : 'not on disk'}, ` +
          `${probe.resolved === null ? `not resolvable (${probe.code})` : `resolves to ${probe.resolved}`}`
      );
    }
    console.log(
      `  declarations on disk   ${declarations.length} .d.ts files, ${kib(declarations.reduce((s, f) => s + f.bytes, 0))}` +
        (generated.length === 0
          ? ', all hand-written (@idfkit/core, @idfkit/schemas, the facade)'
          : `, of which ${generated.length} GENERATED`)
    );
    console.log(`  generated declarations ${generatedBytes} bytes (must be 0)`);
    console.log('');
    console.log(`  no map, tsc --noEmit   ${outTypes.code === 0 ? 'clean' : 'DIAGNOSTICS'} (strict, skipLibCheck off)`);
    console.log(
      `  no map, runs           ${outRun.code === 0 ? `yes: ${outRun.stdout.trim().slice(3, 74)}` : 'NO'}`
    );
    console.log('');
    console.log(`  control: npm install ${TYPE_PACKAGES[0]}`);
    console.log(`    tsc --noEmit         ${inTypes.code === 0 ? 'clean, TypeMap in use' : 'DIAGNOSTICS'}`);
    console.log(
      `    costs                ${kib(inTotal.apparent - total.apparent)} more on disk, which SC-014 does not measure`
    );
    console.log('');

    return verdict(
      findings,
      'a clean install under the shared name carries zero generated declaration bytes, works ' +
        'and type-checks strictly without them, and still accepts a type map when one is added.',
      'declining the generated type packages is not free, or is not possible (SC-014).'
    );
  } finally {
    scratch.dispose();
  }
}

await run(main);
